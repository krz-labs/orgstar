import Foundation
import Testing
@testable import OrgConfig

/// Sources/OrgApp/SettingTexts.swift names every setting's comment and help as a
/// `String(localized:)` literal, so scripts/sync-strings.sh puts them in the string catalog.
/// Rewrite it with `ORGSTAR_WRITE_SETTING_TEXTS=1 swift test --filter SettingTextsTests`.
struct SettingTextsTests {
    static let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()

    static func source() -> String {
        func literal(_ s: String) -> String {
            "\"" + s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
                .replacingOccurrences(of: "\n", with: "\\n") + "\""
        }
        func lines(_ texts: some Sequence<String>, _ comment: String) -> String {
            Set(texts).sorted().map { "        String(localized: \(literal($0)), comment: \"\(comment)\"),\n" }.joined()
        }
        return """
            // Generated by Tests/OrgAppTests/SettingTextsTests.swift; rewrite with
            // ORGSTAR_WRITE_SETTING_TEXTS=1 swift test --filter SettingTextsTests.
            import Foundation

            /// Every config.toml setting's comment and help, for the string catalog; the All Settings
            /// screen looks them up by their English text.
            enum SettingTexts {
                static let all: [String] = [

            """ + lines(UserConfig.settings.map(\.comment), "A config.toml setting, as its comment in the file describes it")
            + lines(UserConfig.help.values, "Help for a config.toml setting") + """
                ]
            }

            """
    }

    @Test func textsFileIsCurrent() throws {
        let file = Self.root.appendingPathComponent("Sources/OrgApp/SettingTexts.swift")
        let wanted = Self.source()
        if ProcessInfo.processInfo.environment["ORGSTAR_WRITE_SETTING_TEXTS"] != nil {
            try wanted.write(to: file, atomically: true, encoding: .utf8)
        }
        #expect((try? String(contentsOf: file, encoding: .utf8)) == wanted, "Sources/OrgApp/SettingTexts.swift is out of date; see SettingTextsTests")
    }
}
